#Import Statistics Library
import statistics
#Assign Marks to the Varible Marks
Marks = (65, 72, 80, 72, 90, 68, 75)
#Compute Mean
Mean = statistics.mean(Marks)
#Compute Median
Median = statistics.median(Marks)
#Compute Mode
Mode = statistics.mode(Marks)
#Print Student Marks
print("Student Marks:", Marks)

#Print Calculated Mean
print("Mean:", Mean)
#Print Calculated Median
print("Median:", Median)
#Print Calculated Mode
print("Mode:", Mode)
